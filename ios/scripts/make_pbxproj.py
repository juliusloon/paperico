def new_id(existing: set[str]) -> str:
    while True:
        candidate = "FE" + "".join(random.choices("0123456789ABCDEF", k=6)) + "".join(
            random.choices(_ALPHABET, k=16)
        )
        if candidate not in existing:
            existing.add(candidate)
            return candidate


